//! CSV exporter for the KEGG coverage survey.
//!
//! Writes five `#` comment lines, a header row, and one data row per
//! **displayed** row — obtained from the same `displayed_rows` chain the table
//! and the dot plot call, so the file matches what the user was looking at.
//!
//! See the `kegg-coverage` capability spec.

use anyhow::{Context, Result};
use std::collections::HashMap;
use std::io::Write;

use crate::app::AnalysisMode;
use crate::coverage::{CoverageResult, DisplayFilters, displayed_rows};

/// Column header line. Order is normative.
const HEADER: &str = "entry_id,entry_name,entry_size,hits,coverage,share,hit_compounds";

/// Separator between the several MS-DIAL metabolite names one compound can
/// carry: `C00031 (D-Glucose | Glucose)`.
///
/// A pipe rather than ` / `, because a slash is a legal character inside an
/// MS-DIAL metabolite name (lipid shorthand such as `PC(16:0/18:1)` is full of
/// them) and a reader splitting the cell on `/` would shred those names. The
/// pipe does not occur in the vocabulary.
///
/// Padded with spaces so a long name list stays readable in a spreadsheet cell,
/// where an unpadded `|` runs the names together. A reader splitting on the
/// bare `|` still recovers the names, with whitespace to trim.
const NAME_SEPARATOR: &str = " | ";

/// Everything the `#` comment lines need, and nothing the computation needed.
pub struct CoverageExportContext<'a> {
    pub mode: AnalysisMode,
    /// Species code in Pathway mode; `"<Level> / <Group>"` in Module mode.
    pub target_label: String,
    /// `Some((selected_group_names, all_group_names, threshold))` when a
    /// metadata `.csv` was supplied; `None` when it was not.
    ///
    /// The group selection and the threshold are the ONLY two inputs on this
    /// route that silently REMOVE features, so two runs of the same dataset
    /// differing only in group selection must not produce byte-identical
    /// provenance headers.
    pub group_record: Option<(Vec<String>, Vec<String>, f64)>,
    /// cpd ID → the user's MS-DIAL metabolite names for the features that
    /// resolved to it. Built by the orchestrator, never by `compute`.
    pub cpd_to_names: &'a HashMap<String, Vec<String>>,
    /// The filter chain in force, so the exporter both records it in the
    /// comment lines and selects rows through `displayed_rows`.
    pub filters: DisplayFilters,
}

/// Write the coverage survey as CSV.
///
/// The `coverage` and `share` cells are decimal FRACTIONS, not percentages,
/// with at least 6 significant digits — the on-screen table shows percentages,
/// but a file that a reader will compute with should not make them divide by
/// 100 first.
///
/// `hit_compounds` lists EVERY hit compound, never truncated (unlike the
/// on-screen column), space-separated inside one quoted field.
pub fn export_coverage_csv<W: Write>(
    writer: &mut W,
    result: &CoverageResult,
    ctx: &CoverageExportContext<'_>,
) -> Result<()> {
    // ASCII only, throughout every comment line. A CSV is opened in whatever
    // the reader's spreadsheet defaults to, and an em-dash rendered there as a
    // tofu box makes the file look corrupted on its very first line.
    writeln!(writer, "# KEGG coverage survey - generated by metabolopan")
        .context("write title line")?;
    writeln!(
        writer,
        "# No statistical test was performed. These are descriptive counts."
    )
    .context("write no-statistics line")?;
    writeln!(
        writer,
        "# Mode: {}; target: {}; detected compounds: {}; entries: {}; \
         entries with no KEGG compounds: {}; min entry size: {}; min hit count: {}; top N: {}",
        mode_label(ctx.mode),
        ctx.target_label,
        result.detected_total,
        result.entries_total,
        result.entries_without_compounds,
        ctx.filters.min_entry_size,
        ctx.filters.min_hit_count,
        ctx.filters.top_n,
    )
    .context("write run-context line")?;
    writeln!(writer, "{}", group_line(&ctx.group_record)).context("write group line")?;
    writeln!(
        writer,
        "# share = hits / detected_total; shares sum to more than 1 because entries share compounds."
    )
    .context("write share note")?;

    // Rows go through `csv::Writer` for RFC-4180-correct quoting. The comment
    // lines above are written raw first so they are never quoted.
    let mut w = csv::Writer::from_writer(writer);
    w.write_record(HEADER.split(','))
        .context("write CSV header")?;
    // The SAME chain the table and the plot use — the file therefore matches
    // what the user saw, by construction rather than by three implementations
    // agreeing.
    for row in displayed_rows(result, ctx.filters) {
        w.write_record([
            row.entry_id.clone(),
            row.entry_name.clone(),
            row.entry_size.to_string(),
            row.hits.to_string(),
            fmt_fraction(row.coverage),
            fmt_fraction(row.share),
            render_hit_compounds(&row.hit_compounds, ctx.cpd_to_names),
        ])
        .context("write CSV row")?;
    }
    w.flush().context("flush CSV writer")?;
    Ok(())
}

fn mode_label(mode: AnalysisMode) -> &'static str {
    match mode {
        AnalysisMode::Pathway => "Pathway",
        AnalysisMode::Module => "Module",
    }
}

/// At least 6 significant digits, as a decimal fraction.
fn fmt_fraction(v: f64) -> String {
    if v.is_finite() {
        format!("{v:.6}")
    } else {
        // Unreachable given the guarded divisions in `compute`, but a NaN
        // silently written as `NaN` would poison a downstream parse.
        String::new()
    }
}

/// The feature-inclusion record.
///
/// Names the FULL selected-group list plus the offered set, because a reader
/// comparing two exports needs to see which groups were dropped, not just how
/// many.
fn group_line(record: &Option<(Vec<String>, Vec<String>, f64)>) -> String {
    match record {
        Some((selected, all, threshold)) => format!(
            "# Sample groups: {} (of {}); detected in >= {:.0}% of a group's samples",
            if selected.is_empty() {
                "none".to_string()
            } else {
                selected.join(", ")
            },
            if all.is_empty() {
                "none".to_string()
            } else {
                all.join(", ")
            },
            threshold * 100.0
        ),
        None => "# Sample groups: none supplied; every feature included.".to_string(),
    }
}

/// Render one row's hit compounds as `<cpd_id> (<name>[ | <name>…])`,
/// space-separated.
///
/// The names are the user's own MS-DIAL `Metabolite name` values — NOT KEGG
/// compound names, so no additional KEGG request is introduced. When one cpd
/// was reached from several features carrying different names, every distinct
/// name is listed. When no name is available the parentheses are omitted
/// entirely, leaving the bare cpd ID: empty parens would read as a lookup that
/// returned nothing rather than one that was never made.
pub(crate) fn render_hit_compounds(
    ids: &[String],
    cpd_to_names: &HashMap<String, Vec<String>>,
) -> String {
    ids.iter()
        .map(|id| match cpd_to_names.get(id) {
            Some(names) if !names.is_empty() => {
                // `cpd_to_names` arrives sorted from the orchestrator; sorting
                // again here keeps the cell deterministic even if a future
                // caller builds the map some other way.
                let mut ns = names.clone();
                ns.sort();
                format!("{id} ({})", ns.join(NAME_SEPARATOR))
            }
            _ => id.clone(),
        })
        .collect::<Vec<_>>()
        .join(" ")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::coverage::{CoverageRow, CoverageSortKey};

    fn row(id: &str, entry_size: usize, hits: usize, compounds: &[&str]) -> CoverageRow {
        CoverageRow {
            entry_id: id.to_string(),
            entry_name: format!("Entry {id}"),
            entry_size,
            hits,
            coverage: hits as f64 / entry_size as f64,
            share: hits as f64 / 100.0,
            hit_compounds: compounds.iter().map(|s| s.to_string()).collect(),
        }
    }

    fn names(pairs: &[(&str, &[&str])]) -> HashMap<String, Vec<String>> {
        pairs
            .iter()
            .map(|(cpd, ns)| {
                (
                    (*cpd).to_string(),
                    ns.iter().map(|s| (*s).to_string()).collect(),
                )
            })
            .collect()
    }

    fn ctx(cpd_to_names: &HashMap<String, Vec<String>>) -> CoverageExportContext<'_> {
        CoverageExportContext {
            mode: AnalysisMode::Pathway,
            target_label: "hsa".into(),
            group_record: Some((
                vec!["Control".into(), "Treated".into()],
                vec!["Control".into(), "QC".into(), "Treated".into()],
                0.5,
            )),
            cpd_to_names,
            filters: DisplayFilters {
                min_entry_size: 3,
                min_hit_count: 1,
                sort_key: CoverageSortKey::Coverage,
                top_n: 20,
            },
        }
    }

    fn result_of(rows: Vec<CoverageRow>) -> CoverageResult {
        CoverageResult {
            entries_without_compounds: 76,
            entries_total: 372,
            rows,
            detected_total: 391,
            detected_in_entries: 264,
        }
    }

    fn render(result: &CoverageResult, ctx: &CoverageExportContext<'_>) -> String {
        let mut buf = Vec::new();
        export_coverage_csv(&mut buf, result, ctx).expect("export succeeds");
        String::from_utf8(buf).expect("utf-8")
    }

    /// A metabolite name containing a slash — lipid shorthand is full of them —
    /// survives intact, which is exactly why the separator is a pipe.
    #[test]
    fn a_slash_in_a_metabolite_name_is_not_the_separator() {
        let map = names(&[("C00157", &["PC(16:0/18:1)", "PC 34:1"])]);
        let cell = render_hit_compounds(&["C00157".into()], &map);
        assert_eq!(cell, "C00157 (PC 34:1 | PC(16:0/18:1))");
        // Splitting on the separator recovers exactly the two names.
        let inner = cell.trim_start_matches("C00157 (").trim_end_matches(')');
        assert_eq!(inner.split('|').count(), 2);
    }

    /// **Item 7.** Every byte the exporter writes is ASCII. A CSV opens in
    /// whatever spreadsheet the reader has, and a multi-byte character rendered
    /// there as a tofu box makes the file look corrupted.
    #[test]
    fn the_whole_csv_is_ascii() {
        let map = names(&[("C00031", &["D-Glucose"])]);
        let out = render(&result_of(vec![row("p1", 42, 18, &["C00031"])]), &ctx(&map));
        assert!(
            out.is_ascii(),
            "non-ASCII in export: {:?}",
            out.chars().filter(|c| !c.is_ascii()).collect::<String>()
        );
        assert_eq!(
            out.lines().next().unwrap(),
            "# KEGG coverage survey - generated by metabolopan"
        );
    }

    /// Five comment lines, then the header, then the data.
    #[test]
    fn csv_shape_is_five_comments_then_header() {
        let map = names(&[]);
        let out = render(&result_of(vec![row("p1", 4, 2, &[])]), &ctx(&map));
        let lines: Vec<&str> = out.lines().collect();
        assert_eq!(lines.len(), 7, "5 comments + header + 1 row: {out}");
        for l in &lines[..5] {
            assert!(l.starts_with('#'), "not a comment: {l}");
        }
        assert_eq!(lines[5], HEADER);
    }

    /// The declaration is line 2, verbatim. It is the one thing a reader who
    /// opens this file in a spreadsheet must not miss.
    #[test]
    fn csv_carries_the_no_statistics_declaration() {
        let map = names(&[]);
        let out = render(&result_of(vec![row("p1", 4, 2, &[])]), &ctx(&map));
        assert_eq!(
            out.lines().nth(1).unwrap(),
            "# No statistical test was performed. These are descriptive counts."
        );
    }

    /// The group record names the full selected list AND the offered set, so
    /// two runs differing only in selection cannot produce identical headers.
    #[test]
    fn the_group_line_records_the_selection_and_the_threshold() {
        let map = names(&[]);
        let out = render(&result_of(vec![row("p1", 4, 2, &[])]), &ctx(&map));
        assert_eq!(
            out.lines().nth(3).unwrap(),
            "# Sample groups: Control, Treated (of Control, QC, Treated); \
             detected in >= 50% of a group's samples"
        );

        let mut c = ctx(&map);
        c.group_record = None;
        let out = render(&result_of(vec![row("p1", 4, 2, &[])]), &c);
        assert_eq!(
            out.lines().nth(3).unwrap(),
            "# Sample groups: none supplied; every feature included."
        );
    }

    /// One name, several names, and none — the three renderings.
    #[test]
    fn hit_compounds_render_id_and_names() {
        let map = names(&[
            ("C00031", &["D-Glucose"]),
            ("C00158", &["Glucose", "D-Glucose"]),
        ]);
        assert_eq!(
            render_hit_compounds(&["C00031".into()], &map),
            "C00031 (D-Glucose)"
        );
        // Names sorted, joined by the pipe.
        assert_eq!(
            render_hit_compounds(&["C00158".into()], &map),
            "C00158 (D-Glucose | Glucose)"
        );
        // No name available → the bare ID, no empty parentheses.
        assert_eq!(render_hit_compounds(&["C00092".into()], &map), "C00092");
        // Space-separated across compounds.
        assert_eq!(
            render_hit_compounds(&["C00031".into(), "C00092".into()], &map),
            "C00031 (D-Glucose) C00092"
        );
    }

    /// **Displayed rows only, in display order** — through the same chain the
    /// table and the plot use.
    #[test]
    fn csv_exports_only_displayed_rows_in_display_order() {
        let map = names(&[]);
        let result = result_of(vec![
            row("small", 2, 2, &[]),   // entry_size < 3
            row("nohits", 10, 0, &[]), // hits < 1
            row("mid", 10, 5, &[]),    // coverage 0.50
            row("best", 4, 4, &[]),    // coverage 1.00
        ]);
        let out = render(&result, &ctx(&map));
        let data: Vec<&str> = out.lines().skip(6).collect();
        assert_eq!(data.len(), 2);
        assert!(data[0].starts_with("best,"), "got {}", data[0]);
        assert!(data[1].starts_with("mid,"), "got {}", data[1]);
    }

    /// `top_n` truncates the file exactly as it truncates the table.
    #[test]
    fn top_n_truncates_the_export() {
        let map = names(&[]);
        let result = result_of(vec![
            row("a", 4, 4, &[]),
            row("b", 10, 5, &[]),
            row("c", 10, 1, &[]),
        ]);
        let mut c = ctx(&map);
        c.filters.top_n = 1;
        let out = render(&result, &c);
        assert_eq!(out.lines().skip(6).count(), 1);
    }

    /// Coverage and share are decimal fractions with 6 digits, not percentages.
    #[test]
    fn coverage_and_share_are_fractions() {
        let map = names(&[]);
        let out = render(&result_of(vec![row("p1", 42, 18, &[])]), &ctx(&map));
        let data = out.lines().nth(6).unwrap();
        // 18 / 42 = 0.428571…
        assert!(data.contains(",0.428571,"), "got {data}");
        assert!(
            !data.contains("42.9"),
            "percentages belong on screen: {data}"
        );
    }

    /// The compound cell is never truncated, unlike the on-screen column.
    #[test]
    fn hit_compounds_are_never_truncated() {
        let ids: Vec<&str> = vec![
            "C00001", "C00002", "C00003", "C00004", "C00005", "C00006", "C00007", "C00008",
        ];
        let map = names(&[]);
        let out = render(&result_of(vec![row("p1", 10, 8, &ids)]), &ctx(&map));
        let data = out.lines().nth(6).unwrap();
        for id in ids {
            assert!(data.contains(id), "{id} missing from {data}");
        }
        assert!(!data.contains('…'));
    }
}
