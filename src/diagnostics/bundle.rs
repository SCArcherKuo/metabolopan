//! Bug report bundle assembly + the per-section text renderers.
//! Per design D6, this module owns:
//! - Cache and input summaries (path/count metadata only — never contents)
//! - The bundle's `README.txt` and modal copy as `const &str` so the two
//!   stay in sync at edit time (D10)
//! - `build_bundle` (added in §7): the zip assembler
//!
//! Privacy invariant (proposal): the bundle MUST NEVER contain raw
//! research data (input files, cache contents, exports). Implementation
//! enforces this by only ever surfacing path/size/mtime metadata for
//! cache files and path/count metadata for inputs.

